			<section id="scope" class="doc-card">
				<p class="section-label">Scope and intent</p>
				<h2>1. Problem class and meaning of the result</h2>
				<p>
					The reinforcement route is a <strong>strip ULS reinforcement screen</strong>. It takes the
					design bending moment per meter of strip width that the beam-on-foundation solver reports
					and returns the tension reinforcement area required to develop that moment, assuming a
					singly reinforced rectangular section and EC2 material laws.
				</p>
				<div class="doc-callout">
					<strong>Scope boundary.</strong> The result is a <em>one-dimensional strip</em>
					reinforcement quantity. It does not produce a two-dimensional bar layout, does not size
					shear links, does not verify serviceability crack widths or deflections, and does not
					account for punching at column heads. It is a preliminary sizing screen that the engineer
					then carries into a dedicated structural design tool.
				</div>
				<div class="symbols">
					<div class="symbols__title">Primary quantities</div>
					<dl class="symbols__list">
						<div class="symbols__row">
							<dt>M<sub>Ed</sub></dt>
							<dd>Design bending moment for the modelled strip width; this is kN·m/m when b = 1.0 m.</dd>
						</div>
						<div class="symbols__row">
							<dt>A<sub>s,req</sub></dt>
							<dd>Required tension reinforcement area for the modelled strip width; this is mm²/m when b = 1.0 m.</dd>
						</div>
						<div class="symbols__row">
							<dt>μ, ω</dt>
							<dd>Dimensionless bending moment and mechanical reinforcement ratio [-].</dd>
						</div>
						<div class="symbols__row">
							<dt>ξ<sub>lim</sub></dt>
							<dd>Limiting neutral-axis ratio for tension-controlled (ductile) failure [-].</dd>
						</div>
					</dl>
				</div>
			</section>

			<section id="solverlink" class="doc-card">
				<p class="section-label">Strip to section handoff</p>
				<h2>2. From the strip-on-foundation solve to the reinforced-concrete section check</h2>
				<p>
					The reinforcement route does not start from a free structural load model. It starts from
					the <strong>ULS bending-moment envelope generated by the Stage 6 strip solver</strong>.
					The current implementation takes the absolute governing bending moment per meter strip
					width, converts the geometric inputs to the modelled strip width, derives the effective
					depth from the EC2 cover route, and then performs a singly reinforced rectangular-section
					check. For normal slab-strip screening this is a 1000 mm strip; for an actual beam or
					strip foundation it follows the entered beam/strip width b.
				</p>
				<div class="doc-callout">
					<strong>Why A<sub>s,req</sub> can rise with h.</strong> In a standalone RC section
					check, increasing h at fixed M<sub>Ed</sub> increases d and would normally reduce
					A<sub>s,req</sub>. In this app M<sub>Ed</sub> is recalculated by the
					beam-on-foundation solver after h changes. If the stiffer strip develops a larger
					moment, that moment increase can outweigh the larger effective depth.
				</div>
				<div class="equations">
					<div class="formula">M<sub>Ed</sub> = |M<sub>ULS,max</sub>|</div>
					<div class="formula">b<sub>w</sub> = 1000 b    (modelled strip width in mm)</div>
					<div class="formula">h<sub>mm</sub> = 1000 h</div>
					<div class="formula">d = h<sub>mm</sub> − c<sub>nom</sub> − φ<sub>bar</sub>/2</div>
					<div class="formula">f<sub>cd</sub> = f<sub>ck</sub>/γ<sub>C</sub>,   f<sub>yd</sub> = f<sub>yk</sub>/γ<sub>S</sub></div>
					<div class="formula">μ = M<sub>Ed</sub> · 10<sup>6</sup> / (b<sub>w</sub> d<sup>2</sup> f<sub>cd</sub>)</div>
					<div class="formula">ω = 1 − √(1 − 2μ)    for the current public screen</div>
					<div class="formula">A<sub>s,req</sub> = ω b<sub>w</sub> d f<sub>cd</sub> / f<sub>yd</sub></div>
					<div class="formula">A<sub>s</sub> = max(A<sub>s,req</sub>, A<sub>s,min</sub>)</div>
				</div>
				<div class="symbols">
					<div class="symbols__title">Implemented handoff quantities</div>
					<dl class="symbols__list">
						<div class="symbols__row">
							<dt>M<sub>ULS,max</sub></dt>
							<dd>Maximum bending moment reported by the strip analysis under the selected ULS combination [kN·m/m].</dd>
						</div>
						<div class="symbols__row">
							<dt>h</dt>
							<dd>Member thickness as entered in Stage 6 [m]. Internally converted to millimetres for the section check.</dd>
						</div>
						<div class="symbols__row">
							<dt>c<sub>nom</sub></dt>
							<dd>Nominal cover returned by the EC2 durability route [mm].</dd>
						</div>
						<div class="symbols__row">
							<dt>φ<sub>bar</sub></dt>
							<dd>Selected bar diameter [mm]. In the current implementation no separate stirrup or link diameter is deducted from d.</dd>
						</div>
					</dl>
				</div>
				<ul class="notes">
					<li>The current public result is based on <strong>the absolute governing moment only</strong>. It is therefore a required steel magnitude, not yet a separate top-versus-bottom reinforcement map.</li>
					<li>The current implementation uses f<sub>cd</sub> = f<sub>ck</sub>/γ<sub>C</sub>. In Belgian practice this is equivalent to taking α<sub>cc</sub> = 1.0 in the EC2 reduction route.</li>
					<li>With b = 1.0 m, the section width is one meter of strip and A<sub>s</sub> is reported in mm²/m. With b different from 1.0 m, A<sub>s</sub> is the total area for the modelled strip width.</li>
				</ul>
			</section>

			<section id="hsensitivity" class="doc-card">
				<p class="section-label">Sensitivity to member depth</p>
				<h2>3. Effect of the strip depth h on A<sub>s,req</sub> (Winkler strip)</h2>
				<p>
					On a rigid-support beam M is fixed by statics, so increasing h reduces μ and reduces
					A<sub>s,req</sub> monotonically. On a Winkler foundation that intuition fails: the
					moment is not given by statics. EI grows as h<sup>3</sup>, λ grows as h<sup>13/16</sup>,
					and the peak moment grows along with λ. Whether A<sub>s,req</sub> increases or decreases
					with h is decided by which power of h dominates: the moment increase or the lever-arm
					gain.
				</p>
				<div class="equations">
					<div class="formula">EI ∝ h<sup>3</sup>,   k<sub>s</sub> ∝ h<sup>−1/4</sup>   (Vesić soft coupling)</div>
					<div class="formula">λ = (4 EI/(b k<sub>s</sub>))<sup>1/4</sup> ∝ h<sup>13/16</sup> ≈ h<sup>0.81</sup></div>
					<div class="formula">d ≈ h − constant ⇒ d ∝ h</div>
					<div class="formula">μ = M<sub>Ed</sub> · 10<sup>6</sup> / (b<sub>w</sub> d<sup>2</sup> f<sub>cd</sub>),   ω ≈ μ for small μ</div>
					<div class="formula">A<sub>s,req</sub> = ω b<sub>w</sub> d f<sub>cd</sub>/f<sub>yd</sub> ≈ M<sub>Ed</sub>/(d f<sub>yd</sub>) for small μ</div>
				</div>
				<p>
					The Hetényi closed forms in <a href="/docs/engineering/beam#hsensitivity">the beam
					chapter §6</a> give M<sub>Ed</sub>(h) for each canonical load case. Carrying those
					exponents through the small-μ approximation A<sub>s,req</sub> ≈ M<sub>Ed</sub>/(d
					f<sub>yd</sub>):
				</p>
				<div class="doc-table-wrap">
					<p class="doc-table-caption">Direction of A<sub>s,req</sub>(h) sensitivity by load case in the small-μ regime.</p>
					<div class="doc-table-scroll">
						<table class="doc-table">
							<thead>
								<tr>
									<th>Load case</th>
									<th>M<sub>Ed</sub> ∝ h<sup>α</sup></th>
									<th>A<sub>s,req</sub> ∝ h<sup>α−1</sup></th>
									<th>Effect of growing h</th>
								</tr>
							</thead>
							<tbody>
								<tr>
									<td>Concentrated load (point or short patch)</td>
									<td>h<sup>0.81</sup></td>
									<td>h<sup>−0.19</sup></td>
									<td>A<sub>s,req</sub> decreases slowly</td>
								</tr>
								<tr>
									<td>Patch UDL (L<sub>patch</sub> &lt; λ)</td>
									<td>h<sup>1.63</sup></td>
									<td>h<sup>0.63</sup></td>
									<td><strong>A<sub>s,req</sub> increases with h</strong></td>
								</tr>
								<tr>
									<td>Full-strip UDL on free-ended strip</td>
									<td>≈ 0</td>
									<td>≈ 0</td>
									<td>A<sub>s,req</sub> hits A<sub>s,min</sub> floor</td>
								</tr>
							</tbody>
						</table>
					</div>
					<p class="doc-table-note">Crossover at α = 1: any load case where the strip-on-foundation solver returns M<sub>Ed</sub> growing faster than h<sup>1</sup> drives A<sub>s,req</sub> upward with h. The patch-UDL case crosses that boundary; the point-load case does not.</p>
				</div>
				<div class="doc-callout">
					<strong>Worked illustration.</strong> Patch UDL load case, b = 1 m, f<sub>ck</sub> = 30
					MPa, c<sub>nom</sub> + φ<sub>bar</sub>/2 = 36 mm, M<sub>Ed,1</sub> = 100 kN·m at
					h<sub>1</sub> = 0.30 m. Going to h<sub>2</sub> = 0.50 m: M<sub>2</sub>/M<sub>1</sub> =
					(0.5/0.3)<sup>1.63</sup> ≈ 2.15, M<sub>Ed,2</sub> ≈ 215 kN·m, d<sub>1</sub> = 264 mm,
					d<sub>2</sub> = 464 mm; μ<sub>1</sub> = 0.072 → A<sub>s,1</sub> ≈ 904 mm²/m,
					μ<sub>2</sub> = 0.050 → A<sub>s,2</sub> ≈ 1094 mm²/m. The +21% jump in A<sub>s</sub>
					comes entirely from the foundation interaction; the section check is unchanged.
				</div>
				<ul class="notes">
					<li>This is a property of the soil-supported analysis, not of the EC2 section check. The μ–ω–A<sub>s</sub> relationship in §5 is monotonic; what changes is the M<sub>Ed</sub> input that the strip solver delivers.</li>
					<li>The closed-form scalings are exact in the small-μ limit (ω ≈ μ). For μ approaching the ductility bound μ<sub>lim</sub> ≈ 0.372 the relationship saturates, but the qualitative direction is preserved.</li>
					<li>If M<sub>Ed</sub> is taken from an external structural model rather than the Stage 6 strip solver, the conventional intuition (more h → less A<sub>s</sub>) does apply. The two checks are separate problems and should be kept separate in the audit trail.</li>
					<li>The same logic applies inversely to k<sub>s</sub>: stiffening the soil column reduces λ and reduces M<sub>Ed</sub> for the patch-UDL case, lowering A<sub>s,req</sub> ∝ k<sub>s</sub><sup>−1/2</sup>.</li>
				</ul>
			</section>

			<section id="kinematics" class="doc-card">
				<p class="section-label">Kinematics and constitutive laws</p>
				<h2>4. Plane sections, concrete law, and steel law</h2>
				<p>
					The formulation is the standard EC2 ULS bending assumption for reinforced concrete:
					plane sections remain plane, strain varies linearly through the depth, concrete
					in tension is ignored, and steel and concrete are each represented by an idealized
					constitutive law.
				</p>
				<div class="equations">
					<div class="formula">ε(y) = ε<sub>c</sub>(y<sub>top</sub> − y)/x linear strain profile</div>
					<div class="formula">σ<sub>c</sub>(ε<sub>c</sub>) = f<sub>cd</sub>[1 − (1 − ε<sub>c</sub>/ε<sub>c2</sub>)<sup>n</sup>]  for 0 ≤ ε<sub>c</sub> ≤ ε<sub>c2</sub></div>
					<div class="formula">σ<sub>c</sub>(ε<sub>c</sub>) = f<sub>cd</sub>                         for ε<sub>c2</sub> ≤ ε<sub>c</sub> ≤ ε<sub>cu2</sub></div>
					<div class="formula">n = 2,   ε<sub>c2</sub> = 2.0‰,   ε<sub>cu2</sub> = 3.5‰  (f<sub>ck</sub> ≤ 50 MPa)</div>
					<div class="formula">ε<sub>s</sub> = ε<sub>cu2</sub>(d − x)/x     at the tension steel level</div>
					<div class="formula">σ<sub>s</sub>(ε<sub>s</sub>) = E<sub>s</sub> ε<sub>s</sub>  for |ε<sub>s</sub>| ≤ f<sub>yd</sub>/E<sub>s</sub></div>
					<div class="formula">σ<sub>s</sub>(ε<sub>s</sub>) = sign(ε<sub>s</sub>) · f<sub>yd</sub>     beyond yield (horizontal branch adopted)</div>
					<div class="formula">EC2 general form: f<sub>cd</sub> = α<sub>cc</sub> f<sub>ck</sub>/γ<sub>C</sub>,   f<sub>yd</sub> = f<sub>yk</sub>/γ<sub>S</sub></div>
					<div class="formula">Current public implementation: f<sub>cd</sub> = f<sub>ck</sub>/γ<sub>C</sub>,   f<sub>yd</sub> = f<sub>yk</sub>/γ<sub>S</sub></div>
				</div>
				<div class="symbols">
					<div class="symbols__title">Notation</div>
					<dl class="symbols__list">
						<div class="symbols__row">
							<dt>ε<sub>c</sub>, ε<sub>c2</sub>, ε<sub>cu2</sub></dt>
							<dd>Concrete compressive strain, strain at peak, and ultimate strain [-]. Values for f<sub>ck</sub> ≤ 50 MPa.</dd>
						</div>
						<div class="symbols__row">
							<dt>n</dt>
							<dd>Exponent of the parabolic branch (n = 2 for normal strength).</dd>
						</div>
						<div class="symbols__row">
							<dt>x</dt>
							<dd>Neutral-axis depth from the compressed fibre [m].</dd>
						</div>
						<div class="symbols__row">
							<dt>ε<sub>s</sub></dt>
							<dd>Tension-steel strain obtained from the strain triangle at depth d.</dd>
						</div>
						<div class="symbols__row">
							<dt>E<sub>s</sub></dt>
							<dd>Steel Young modulus, 200 GPa.</dd>
						</div>
						<div class="symbols__row">
							<dt>α<sub>cc</sub></dt>
							<dd>Sustained-load coefficient. The current public route is consistent with α<sub>cc</sub> = 1.0.</dd>
						</div>
						<div class="symbols__row">
							<dt>γ<sub>C</sub>, γ<sub>S</sub></dt>
							<dd>Partial material factors for concrete and steel. Default ULS: γ<sub>C</sub> = 1.50, γ<sub>S</sub> = 1.15.</dd>
						</div>
					</dl>
				</div>
